#!/usr/bin/env python3
"""Generate macro-off legacy kernels without touching the staged source."""
from pathlib import Path
import hashlib, json, shutil, subprocess
root=Path(__file__).resolve().parent
src=root/'stage/FluidX3D_on/src'
ref=root.parent.parent/'R21.4a_T15_second_layer_WM/continuation8b_20261119_0026'
# R21.4a_T17_periodic_ABL is sibling of R21.4a_T15_second_layer_WM
ref=root.parents[1]/'R21.4a_T15_second_layer_WM/continuation8b_20261119_0026'
results={}
for name, transform in {'off':('GROUND_WALL_MODEL','SECOND_LAYER_WM'),'on':(),'k3':()}.items():
    d=root/'legacy_check_v6'/name
    d.mkdir(parents=True,exist_ok=True)
    for fn in ('kernel.cpp','kernel.hpp','defines.hpp'):
        (d/fn).write_bytes((src/fn).read_bytes())
    if name=='k3':
        k=(d/'kernel.cpp').read_text()
        replacements=(
            ('const ulong b=a+(ulong)xy;\n        if(first==0u || first+1u>=def_Nz', 'const ulong b=a+2ul*(ulong)xy; // k=3 sensitivity: 2.5 m above numerical wall\n        if(first==0u || first+2u>=def_Nz'),
            ('if(first==0u || first+1u>=def_Nz) { new_stress', 'if(first==0u || first+2u>=def_Nz) { new_stress'),
            ('if(first==0u || first+2u>=def_Nz) { new_stress[col]=0.0f;new_stress[xy+col]=0.0f;return; }\n    const ulong a=(ulong)col+(ulong)first*(ulong)xy, b=a+(ulong)xy;', 'if(first==0u || first+2u>=def_Nz) { new_stress[col]=0.0f;new_stress[xy+col]=0.0f;return; }\n    const ulong a=(ulong)col+(ulong)first*(ulong)xy, b=a+2ul*(ulong)xy;'),
            # The archived k3 stress updater intentionally retained b=a+xy;
            # only the other matching-layer read changed to k=3.
            ('log((1.5f+def_ground_z0_lattice)/def_ground_z0_lattice)', 'log((2.5f+def_ground_z0_lattice)/def_ground_z0_lattice)')
        )
        for old,new in replacements:
            assert old in k,old
            k=k.replace(old,new)
        # Reproduce the archived k3-only scope fix, not an alteration to
        # the T17 production source. Keep off/on generated bytes untouched.
        before='''\tfloat applied_ground_fx=0.0f;
\tif(ground_first_fluid) {'''
        after='''\tfloat applied_ground_fx=0.0f;
\t\t) + "#ifdef SECOND_LAYER_WM" + R(
\tfloat applied_ground_fy=0.0f;
\tfloat applied_ground_tau_abs=0.0f;
\t\t) + "#endif" + R(
\tif(ground_first_fluid) {'''
        assert k.count(before)==1
        k=k.replace(before,after,1)
        scoped='''        float applied_ground_fy=0.0f;
        float applied_ground_tau_abs=0.0f;
        const uint col=ground_xyz.x+def_Nx*ground_xyz.y;'''
        assert k.count(scoped)==1
        k=k.replace(scoped,'        const uint col=ground_xyz.x+def_Nx*ground_xyz.y;',1)
        (d/'kernel.cpp').write_text(k)
    defines=(d/'defines.hpp').read_text()
    for macro in transform:
        token='#define '+macro+' '
        assert defines.count(token)==1,(name,macro)
        defines=defines.replace(token,'//#define '+macro+' ',1)
    (d/'defines.hpp').write_text(defines)
    exe=d/'emit'
    cmd=['g++','-std=c++17','-O0','-I',str(src),str(d/'kernel.cpp'),str(root/'emit_kernel.cpp'),'-o',str(exe)]
    p=subprocess.run(cmd,text=True,capture_output=True)
    (d/'build.log').write_text(p.stdout+p.stderr+f'\nexit={p.returncode}\n')
    assert p.returncode==0,(name,p.stderr[-1000:])
    out=d/'generated.cl'
    p=subprocess.run([str(exe),str(out)],text=True,capture_output=True)
    assert p.returncode==0,(name,p.stderr)
    frozen=ref/f'{name}_new_kernel_container.cl'
    a,b=out.read_bytes(),frozen.read_bytes()
    results[name]={'generated':str(out),'frozen':str(frozen),'generated_sha256':hashlib.sha256(a).hexdigest(),'frozen_sha256':hashlib.sha256(b).hexdigest(),'generated_bytes':len(a),'frozen_bytes':len(b),'byte_equal':a==b}
    print(name, results[name],flush=True)
(root/'LEGACY_BYTE_CHECK_v6.json').write_text(json.dumps(results,indent=2)+'\n')
assert all(v['byte_equal'] for v in results.values()),'legacy macro-off OpenCL mismatch'
