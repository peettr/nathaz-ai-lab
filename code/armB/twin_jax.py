"""JAX transplant of frozen L30.1f v8b/plant.py (numpy original is read-only).

The history uses travelled distance and causal searchsorted, not a fixed-time delay.
The noise tape is generated by numpy's original RNG and held fixed in autodiff.
Lux soft first-zero: survival_i = prod_{j=1..i} sigmoid(acf_j/epsilon),
soft trapezoid = sum_i survival_i * dt*(acf_{i-1}+acf_i)/2,
with the original n//4 cap. epsilon is explicit; gate assesses its bias.
"""
import numpy as np
import jax
import jax.numpy as jnp
from jax import lax

jax.config.update('jax_enable_x64', True)
Z=jnp.asarray([.05,.10,.15,.198,.25,.30,.525,.725,.95,1.15,1.375,1.575])
ROW_Z=(jnp.arange(8)+.5)*3/13
DISTANCE=26.3


def arrays(p,terrain):
    z=Z
    rough=jnp.exp(-z/p.z_i)*terrain[1]+(1-jnp.exp(-z/p.z_i))*terrain[0]
    h=jnp.interp(z,jnp.array([.05,.65,1.575]),jnp.array([p.h650*p.h50_ratio,p.h650,p.h650*1.05]))
    h=h*(1-.04*rough/.16)
    iu=(.115+.21*rough/.16)*(z/.198)**(-p.gamma)
    lux=1.16-.8*rough/.16
    w=jnp.exp(-.5*((z[:,None]-ROW_Z[None,:])/p.width)**2)
    return h,iu,lux,w/w.sum(axis=1,keepdims=True)


def tape(p,n,seed,with_noise=True):
    """Match original Plant.run's drift draw and normal tape after noiseless settling."""
    rng=np.random.default_rng(seed)
    if not with_noise:return 1.,jnp.zeros((n,12))
    repeat=1+rng.normal(0,p.drift)
    return repeat,jnp.asarray(rng.normal(size=(n,12)))


def forward(p,main,rows,terrain,seed=None,settle=0,checkpoint=False):
    """Continuous state for one full command, sample output from index settle.

    The noise RNG activates at sampling only, as in original score().
    Input rows is (8,n); 'main' is scalar or (n,). All physical state persists.
    """
    rows=jnp.asarray(rows); n=rows.shape[1]
    main=jnp.broadcast_to(jnp.asarray(main),(n,))
    h,iu,lux,w=arrays(p,jnp.asarray(terrain))
    dt=1/p.fs; L=1/(18*p.tau_ref)
    a_n=jnp.exp(-dt/p.main_tau);a_q=jnp.exp(-dt/p.tau_q);a_p=jnp.exp(-dt/p.tau_p)
    cmd0=rows[:,0];avg0=cmd0.mean();cp0=cmd0-avg0
    eq0=(1-p.b)*main[0]**2+p.b*avg0*jnp.abs(avg0)
    q0=jnp.sqrt(jnp.maximum(0,eq0))
    xs=jnp.full(n+1,jnp.inf,dtype=jnp.float64).at[0].set(0.)
    cs=jnp.zeros((n+1,8),dtype=jnp.float64).at[0].set(cp0)
    rep,normal=tape(p,n-settle,seed,seed is not None)
    normal=jnp.concatenate([jnp.zeros((settle,12)),normal],axis=0)
    al0=jnp.zeros(12)
    carry=(main[0],cmd0,avg0,cp0,q0,jnp.float64(0),xs,cs,al0,jnp.float64(1.),jnp.bool_(True))
    def step(c,inp):
        N,F,Q,P,q,x,xh,ch,noise,min_ratio,valid=c
        k,nc,cmd,eps=inp
        N=a_n*N+(1-a_n)*nc
        F=F+jnp.clip(cmd-F,-p.ffm_rate*dt,p.ffm_rate*dt)
        avg=F.mean(); contrast=F-avg
        Q=a_q*Q+(1-a_q)*avg;P=a_p*P+(1-a_p)*contrast
        fq=(1-p.s_q)*avg+p.s_q*Q;cp=(1-p.s_p)*contrast+p.s_p*P
        e=(1-p.b)*N**2+p.b*fq*jnp.abs(fq)
        q=jnp.maximum(0.,q+.5*dt*L*(e-q*q))
        q=jnp.maximum(0.,q+.5*dt*L*(e-q*q))
        x=x+p.kappa*q*dt
        xh=xh.at[k+1].set(x);ch=ch.at[k+1].set(cp)
        sx=jnp.maximum(0.,x-DISTANCE)
        # Search among all slots; unfilled slots remain 0. Strict causal nearest-left.
        j=jnp.clip(jnp.searchsorted(xh,sx,side='right')-1,0,k)
        j=jnp.minimum(j,k)
        left=xh[j];right=xh[j+1]
        frac=jnp.clip((sx-left)/jnp.maximum(right-left,1e-20),0.,1.)
        source=ch[j]*(1-frac)+ch[j+1]*frac
        vel=h*q+p.c*(w@source)
        ratio=jnp.min(vel/jnp.maximum(h*q,1e-12))
        min_ratio=jnp.minimum(min_ratio,ratio);valid=jnp.logical_and(valid,ratio>=.5)
        alpha=jnp.exp(-dt*jnp.maximum(vel,.1)/jnp.maximum(lux,.05))
        newnoise=alpha*noise+jnp.sqrt(1-alpha**2)*eps
        active=k>=settle
        noise=jnp.where(active,newnoise,noise)
        noisy=jnp.where(active,rep*(vel+noise*iu*jnp.maximum(vel,0)),vel)
        return (N,F,Q,P,q,x,xh,ch,noise,min_ratio,valid),noisy
    if checkpoint:step=jax.checkpoint(step)
    final,out=lax.scan(step,carry,(jnp.arange(n),main,rows.T,normal))
    return out[settle:].T,final[-2],final[-1]


def metrics(series,dt,softness=1e-4):
    """Soft first-zero ACF; original unbiased noncircular ACF and n//4 cap."""
    n=series.shape[-1];mean=series.mean(axis=-1)
    fl=series-mean[:,None]
    acf=jnp.fft.irfft(jnp.abs(jnp.fft.rfft(fl,n=2*n,axis=-1))**2,n=2*n,axis=-1)[:,:n]/jnp.arange(n,0,-1)
    acf=acf/jnp.maximum(acf[:,:1],1e-12)
    cut=n//4
    a=acf[:,:cut+1]
    survival=jnp.cumprod(jax.nn.sigmoid(a[:,1:]/softness),axis=-1)
    lux=jnp.maximum(0.,mean*jnp.sum(dt*.5*(a[:,:-1]+a[:,1:])*survival,axis=-1))
    return {'u':mean,'Iu':jnp.std(fl,axis=-1)/jnp.maximum(mean,1e-6),'Lux':lux}


def predict(p,cmd,seed=1001,command_seed=2001,duration=1800.,softness=1e-4,checkpoint=False):
    """Generate an original fixed-seed command; JAX forward/statistics only."""
    from pathlib import Path
    import sys
    src=Path(__file__).resolve().parent/'from_L30.1f'/'v8b'
    sys.path.insert(0,str(src))
    from plant import commands
    x=np.asarray(cmd)
    wave=commands(p,float(x[0]),x[1:9],x[9:17],x[17:25],x[25:27],duration+120,command_seed)
    settle=int(round(120*p.fs))
    series,ratio,valid=forward(p,wave['main'],wave['rows'],wave['terrain'],seed,settle,checkpoint)
    return metrics(series,1/p.fs,softness),ratio,valid
