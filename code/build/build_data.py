#!/usr/bin/env python3
"""L26.26 page 1: build embedded data.json from R21.6 read-only sources.
Every number shown on the page must come from this file (key 'nums' or the series).
Sources are opened read-only; nothing is written outside this directory.
"""
from pathlib import Path
import csv, json, hashlib, re

HERE = Path(__file__).resolve().parent
DWT = Path('./21_Digital_Wind_Tunnel')
SRC = DWT / '04_Outputs/u3dwind_check'
REP = DWT / '05_Projects/R21.6_U3DWind_对照与可用性/结题报告'
sources = {}

def rd(p):
    b = p.read_bytes()
    sources[str(p.relative_to(DWT))] = hashlib.sha256(b).hexdigest()
    return b.decode('utf-8')

def rows(p):
    return list(csv.DictReader(rd(p).splitlines()))

# --- headline numbers: parsed from numbers_v3.tex (generated by R21.6 make_figs_v3.py)
tex = rd(REP / 'numbers_v3.tex')
macros = dict(re.findall(r'\\newcommand\{\\(\w+)\}\{([^}]*)\}', tex))
want = {
    'MorphArea': ('发布版建筑覆盖率', '%'), 'MorphHeight': ('发布版建筑中位高', 'm'),
    'PaperArea': ('论文 Table 3 香港建筑覆盖率', '%'), 'PaperHeight': ('论文 Table 3 香港建筑中位高', 'm'),
    'FluxMinimum': ('截面流量最低值 Q/Q(0)', ''), 'FluxDistance': ('最低处距入口', 'km'),
    'FluxDecline': ('截面流量最大下降', '%'), 'TopShare': ('该处累计顶面流出占入口流量', '%'),
    'ResidualShare': ('该处未闭合余量', '%'), 'PublishedOutlet': ('末端 Q/Q(0)', ''),
    'QgapA': ('种子100重算与发布版最大归一化流量差', ''), 'QgapB': ('种子101与发布版最大归一化流量差', ''),
    'DapMax': ('重算对发布版逐格差 D_AP 最大分段中位数', 'U_ref'),
    'SeedMin': ('两种子逐格差 D_AB 分段中位数下限', 'U_ref'), 'SeedMax': ('两种子逐格差 D_AB 分段中位数上限', 'U_ref'),
    'Rratio': ('种子差与发布差比值 R', ''), 'Nratio': ('有效层段比值个数', ''),
    'SpeedCoreMin': ('3/6 m/s 归一化风速差前 26 km 分段中位数下限', ''), 'SpeedMax': ('同上上限', ''),
    'SpeedMin': ('28–30 km 段中位数', ''), 'AverageSeconds': ('Colab 重算末统计窗', 's'),
}
nums = {}
tex_lines = tex.splitlines()
for k, (label, unit) in want.items():
    line = next(i + 1 for i, l in enumerate(tex_lines) if '\\' + k + '}' in l)
    nums[k] = {'text': macros[k], 'value': float(macros[k]), 'label': label, 'unit': unit,
               'source': str((REP / 'numbers_v3.tex').relative_to(DWT)), 'line': line}

# --- series
fl = rows(SRC / 'hk_post_v2/flux_hongkong.csv')
q0 = float(fl[0]['Q_m3_s'])
flux = {'x_km': [round(float(r['distance_from_inlet_m']) / 1000, 3) for r in fl],
        'published_Q_Q0': [float(r['Q_Q0']) for r in fl],
        'top_cum_over_Q0': [float(r['top_cumulative_m3_s']) / q0 for r in fl]}
# sign: source convention kept (positive = cumulative outflow through top), as in R21.6 report fig 1
flux['residual_over_Q0'] = [1 - q - t for q, t in zip(flux['published_Q_Q0'], flux['top_cum_over_Q0'])]

fc = rows(SRC / 'culbm_rerun_colab/compare_v2b_lead/r216_compare_v2b/flux_compare.csv')
rerun = {'x_km': [round(float(r['distance_from_inlet_m']) / 1000, 3) for r in fc],
         'published_Q_Q0': [float(r['published_Q_Q0']) for r in fc],
         'rerun_Q_Q0': [float(r['rerun_Q_Q0']) for r in fc]}

qc = rows(SRC / 'culbm_seed_colab/final/Q_compare.csv')
seedQ = {'x_km': [round(float(r['distance_from_inlet_m']) / 1000, 3) for r in qc],
         'A_seed100': [float(r['Q_A_Q0']) for r in qc], 'B_seed101': [float(r['Q_B_Q0']) for r in qc],
         'P_published': [float(r['Q_P_Q0']) for r in qc]}

ds = rows(SRC / 'culbm_seed_colab/final/D_segments.csv')
seg = {}
for r in ds:
    z = r['z_m']
    seg.setdefault(z, []).append({k: float(r[k]) for k in ['distance_start_m', 'distance_end_m', 'D_AB_p10', 'D_AB_median', 'D_AB_p90', 'D_AP_median', 'D_BP_median']})
for z in seg:
    seg[z].sort(key=lambda d: d['distance_start_m'])

sp = rows(SRC / 'hk_post_v2/comparison_speed_03_06.csv')
speed = [{'x_start_m': float(r['x_start_m']), 'x_end_m': float(r['x_end_m']), 'p10': float(r['p10']),
          'median': float(r['median']), 'p90': float(r['p90'])} for r in sp
         if float(r['x_end_m']) - float(r['x_start_m']) == 2000.0]
speed.sort(key=lambda d: d['x_start_m'])

data = {
    'title': 'U3DWind 发布版 v2 香港 u06_annual / 270° 均值风场核查（R21.6）',
    'nums': nums,
    'flux': flux, 'rerun': rerun, 'seedQ': seedQ, 'seed_segments_by_z_m': seg, 'speed_03_06_100mAGL': speed,
    'notes': {
        'flux': 'Q 为体积流量 Σ_fluid u·Δy·Δz；顶面累计流出沿用源表符号（正为流出）；余量 = 1 − Q/Q0 − 顶面累计流出比。',
        'seed': 'D_AB 为两种子逐格均值差（以 U_ref 归一化）的 2 km 分段中位数；95/195/395 m 为笛卡尔层高度。',
        'speed': '|U03/3 − U06/6| 中位数，100 m AGL，2 km 分段；与种子差的 95 m 笛卡尔层不是同一高度，不能同层比较。',
    },
    'verdict': '只作数据管道测试，不作经实测校验的城市均值参考（限发布版 v2 香港 u06_annual/270°）',
    'references': [
        'Zhou, Wei, Xia, Xing, Jiang, Yang, Jia (2027). U3DWind: A low altitude wind field dataset and benchmark for urban air mobility. Aerospace Science and Technology 180, 114092. doi:10.1016/j.ast.2026.114092',
        'Cao, Wei, Xia, Jia, Xing, Yang (2026). Urban Wind Effects on UAV Operations in Building-Dense Low-Altitude Airspace. arXiv:2609.18974',
        'Han et al. (2026). Near-real-time, meter-scale 3D urban wind modeling for low-altitude micrometeorology: numerical verification of a GPU-accelerated lattice Boltzmann framework. Developments in the Built Environment. doi:10.1016/j.dibe.2026.101057',
    ],
    'sources_sha256': sources,
}
(HERE / 'data.json').write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding='utf-8')
# quick self-consistency against headline numbers
mn = min(flux['published_Q_Q0']); i = flux['published_Q_Q0'].index(mn)
print('min Q/Q0', round(mn, 4), 'at km', flux['x_km'][i], 'top', round(flux['top_cum_over_Q0'][i] * 100, 1), 'resid', round(flux['residual_over_Q0'][i] * 100, 1))
print('max |rerun-pub|', round(max(abs(a - b) for a, b in zip(rerun['rerun_Q_Q0'], rerun['published_Q_Q0'])), 4))
print('max |B-P|', round(max(abs(a - b) for a, b in zip(seedQ['B_seed101'], seedQ['P_published'])), 4))
meds = [d['D_AB_median'] for z in seg for d in seg[z]]
print('D_AB med range', round(min(meds), 3), round(max(meds), 3), 'n', len(meds))
print('speed med first 13', round(min(d['median'] for d in speed[:13]), 3), round(max(d['median'] for d in speed[:13]), 3), 'last', round(speed[-1]['median'], 3))
print('size', (HERE / 'data.json').stat().st_size)
