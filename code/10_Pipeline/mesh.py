"""Generate a 2D square-to-offset-circle O grid in Fluent ASCII mesh format.

Geometry/cells are generated by this Python module, NOT by Fluent Meshing.
The separate PyFluent Meshing session imports, checks and exports this mesh.
"""
import math
from pathlib import Path


def generate(path, side_divisions=24, radial_divisions=40, beta=8.0):
    if side_divisions < 4 or radial_divisions < 4 or beta <= 0:
        raise ValueError("invalid mesh controls")
    # Square perimeter CCW, starting at lower right corner.
    n = 4 * side_divisions
    square = []
    for j in range(side_divisions):
        square.append((.5, -.5+j/side_divisions))
    for j in range(side_divisions):
        square.append((.5-j/side_divisions, .5))
    for j in range(side_divisions):
        square.append((-.5, .5-j/side_divisions))
    for j in range(side_divisions):
        square.append((-.5+j/side_divisions, -.5))
    nodes = []
    for j, (x, y) in enumerate(square):
        theta = math.atan2(y, x)
        c, s = math.cos(theta), math.sin(theta)
        t = 5*c + math.sqrt(900 - 25*s*s)
        for i in range(radial_divisions+1):
            f = math.expm1(beta*i/radial_divisions)/math.expm1(beta)
            nodes.append((x*(1-f)+f*t*c, y*(1-f)+f*t*s))
    def node(j,i):
        return (j % n)*(radial_divisions+1)+i+1
    cells=[]
    for j in range(n):
        for i in range(radial_divisions):
            cells.append((node(j,i),node(j,i+1),node(j+1,i+1),node(j+1,i)))
    # The perimeter and each cell follow a counter-clockwise ring. Fluent's
    # 2D face convention puts c0 to the LEFT of n0 -> n1 (c1 to the right).
    # Verify geometry as well as topology before writing any mesh.
    min_area = math.inf
    for ic, cell in enumerate(cells, 1):
        twice_area = sum(nodes[a-1][0]*nodes[b-1][1] -
                         nodes[b-1][0]*nodes[a-1][1]
                         for a,b in zip(cell,cell[1:]+cell[:1]))
        if not math.isfinite(twice_area) or twice_area <= 0:
            raise ValueError(f'non-positive oriented cell area: {ic} {twice_area}')
        min_area = min(min_area, twice_area/2)
    edges={}
    for ic, cell in enumerate(cells,1):
        for a,b in zip(cell,cell[1:]+cell[:1]):
            key=tuple(sorted((a,b)))
            edges.setdefault(key,[]).append((a,b,ic))
    faces={2:[],3:[],4:[],5:[]}
    for owners in edges.values():
        a,b,first=owners[0]
        if len(owners)==2:
            if owners[1][:2] != (b,a):
                raise ValueError(f'inconsistent interior edge orientation: {a},{b}')
            faces[5].append((a,b,first,owners[1][2]))
        else:
            ax,ay=nodes[a-1]; bx,by=nodes[b-1]
            if max(math.hypot(ax,ay),math.hypot(bx,by))<1:
                zone=2 # wall
            else:
                zone=4 if (ax+bx)/2>5 else 3 # outlet/inlet
            faces[zone].append((a,b,first,0))
    total_faces=sum(map(len,faces.values()))
    centroids = [None] + [tuple(sum(nodes[k-1][d] for k in cell)/4
                                   for d in (0,1)) for cell in cells]
    for zone, seq in faces.items():
        for a,b,c0,c1 in seq:
            x0,y0=nodes[a-1]; x1,y1=nodes[b-1]
            def cross(cell):
                x,y=centroids[cell]
                return (x1-x0)*(y-y0)-(y1-y0)*(x-x0)
            if c0 == 0 or cross(c0) <= 0 or (c1 and cross(c1) >= 0):
                raise ValueError(f'left-handed face zone={zone} edge={a},{b} cells={c0},{c1}')
    out=Path(path); out.parent.mkdir(parents=True,exist_ok=True)
    with out.open('w') as fh:
        fh.write('(0 "sqcyl2d structured O-grid; source mesh is Python-generated")\n(2 2)\n')
        fh.write(f'(10 (0 1 {len(nodes):x} 0))\n(12 (0 1 {len(cells):x} 0))\n')
        fh.write(f'(10 (1 1 {len(nodes):x} 1 2)(\n')
        for x,y in nodes: fh.write(f'{x:.15g} {y:.15g}\n')
        fh.write('))\n')
        fh.write(f'(13 (0 1 {total_faces:x} 0))\n')
        start=1
        for zone,kind,name in ((2,3,'cylinder'),(3,10,'inlet'),(4,5,'outlet'),(5,2,'fluid-interior')):
            seq=faces[zone]; end=start+len(seq)-1
            fh.write(f'(13 ({zone:x} {start:x} {end:x} {kind:x} 2)(\n')
            for a,b,c0,c1 in seq: fh.write(f'{a:x} {b:x} {c0:x} {c1:x}\n')
            fh.write('))\n')
            start=end+1
        fh.write(f'(12 (6 1 {len(cells):x} 1 3))\n')
        for z,kind,name in ((2,'wall','cylinder'),(3,'velocity-inlet','inlet'),(4,'pressure-outlet','outlet'),(5,'interior','fluid-interior'),(6,'fluid','fluid')):
            fh.write(f'(45 ({z:x} {kind} {name})())\n')
    return {'nodes':len(nodes),'cells':len(cells),'faces':total_faces,
            'min_oriented_area':min_area,'orientation':'all positive, c0 left / c1 right',
            'zones':{k:len(v) for k,v in faces.items()}}
