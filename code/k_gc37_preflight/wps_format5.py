#!/usr/bin/env python3
"""WPS format-5 lat/lon slab writer and independent framing/readback.

Header/projection follow NCAR era5_to_int WPSUtils.py and project's v22 reader.
No geophysical input is generated by this module.
"""
import struct,hashlib,pathlib,numpy as np

def record(handle,payload):
 prefix=struct.pack('>I',len(payload));handle.write(prefix);handle.write(payload);handle.write(prefix)
def fixed(s,n): return str(s).encode('ascii').ljust(n,b' ')[:n]
def write_field(handle,date,forecast_h,source,field,units,description,pressure_pa,lat0,lon0,dlat,dlon,data):
 a=np.asarray(data,dtype='>f4');assert a.ndim==2 and np.isfinite(a).all(); ny,nx=a.shape
 assert 0<=pressure_pa<=300000 and dlat>0 and dlon>0
 hdr=b''.join((fixed(date,24),struct.pack('>f',float(forecast_h)),fixed(source,32),fixed(field,9),fixed(units,25),fixed(description,46),struct.pack('>fiii',float(pressure_pa),nx,ny,0)))
 assert len(hdr)==156
 record(handle,struct.pack('>I',5));record(handle,hdr)
 record(handle,fixed('SWCORNER',8)+struct.pack('>fffff',lat0,lon0,dlat,dlon,6371.229))
 record(handle,struct.pack('>i',0)) # earth-relative winds
 record(handle,a.tobytes(order='C'))
def read_records(path):
 with open(path,'rb') as h:
  while (prefix:=h.read(4)):
   if len(prefix)!=4:raise ValueError('short_prefix')
   n,=struct.unpack('>I',prefix)
   if n>500000000:raise ValueError('oversize_record')
   data=h.read(n)
   if len(data)!=n or h.read(4)!=prefix:raise ValueError('bad_record')
   yield data
def readback(path):
 r=iter(read_records(path));fields=[]
 while True:
  try:vers=next(r)
  except StopIteration:break
  if vers!=struct.pack('>I',5):raise ValueError('bad_version')
  hdr=next(r);proj=next(r);wind=next(r);slab=next(r)
  if len(hdr)!=156 or len(proj)!=28 or len(wind)!=4 or not proj.startswith(b'SWCORNER'):raise ValueError('bad_header')
  lev,nx,ny,iproj=struct.unpack('>fiii',hdr[140:156]);
  if iproj!=0 or len(slab)!=nx*ny*4:raise ValueError('grid mismatch')
  a=np.frombuffer(slab,dtype='>f4').reshape((ny,nx));
  if not np.isfinite(a).all():raise ValueError('nonfinite')
  fields.append({'field':hdr[60:69].decode().strip(),'units':hdr[69:94].decode().strip(),'level_pa':int(round(lev)),'nx':nx,'ny':ny,'min':float(a.min()),'max':float(a.max())})
 return {'file':str(path),'records':len(fields),'fields':fields,'sha256':hashlib.file_digest(open(path,'rb'),'sha256').hexdigest()}
