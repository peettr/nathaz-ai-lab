#!/usr/bin/env python3
"""B1 v2 (a) offline chain CANDIDATE; do not execute before Lead freeze.
Input: BEST node CSV with event,time_utc,lat,lon,vmax_kt,pc_hpa,penv_hpa,
rmw_nmi; station CSV with event,station,lat,lon,device_type,height_m,
historical_verified; hourly CSV with event,station,time_utc,sknt,gust_sknt.
These are independent staged inputs, not generated by this script. BEST wind radii
fitting and KZ-derived pressures MUST be upstream/audited before any run.
"""
import argparse,csv,json,math,statistics,sys
from collections import defaultdict
from datetime import datetime,timezone,timedelta
from pathlib import Path
UTC=timezone.utc

def rows(path):
    with open(path,newline='') as f:return list(csv.DictReader(f))

def dt(value):return datetime.fromisoformat(value.replace('Z','+00:00')).astimezone(UTC)

def station_allowed(r):
    return r['device_type']=='ASOS' and r['historical_verified']=='yes' and 8<=float(r['height_m'])<=12

def kz_pressure(vmax_kt, lat, motion_kt, penv_hpa, v500_kt):
    """Knaff--Zehr 2007 Eq 4--7, PDF 5/10; not called with obs."""
    x=.1147+.0055*vmax_kt-.001*(lat-25)
    rmax=66.785-.09102*vmax_kt+1.0619*(lat-25)
    if vmax_kt<15 or rmax<=0 or x<=0:raise ValueError('KZ outside domain')
    v500c=vmax_kt*(rmax/500)**x
    s=v500_kt/v500c;vsrm=vmax_kt-1.5*motion_kt**.63
    pc=penv_hpa+23.286-.483*vsrm-(vsrm/24.254)**2-12.587*s-.483*lat
    if not 0<penv_hpa-pc<250:raise ValueError('unphysical KZ deficit')
    return pc

def rmw_prior_nmi(vmax_kt,lat):
    return 36.1-.0492*vmax_kt+.5740*(lat-25)

def window_qc(hours,landfall,tstar):
    """One-hour METAR bins; no data substitution, documented censoring."""
    start=landfall-timedelta(hours=12);end=landfall+timedelta(hours=12)
    d={dt(r['time_utc']).replace(minute=0,second=0,microsecond=0):r for r in hours if r.get('sknt') not in ('',None)}
    valid={t:r for t,r in d.items() if float(r['sknt'])>=0}
    slot=[start.replace(minute=0,second=0,microsecond=0)+timedelta(hours=k) for k in range(24)]
    coverage=sum(t in valid for t in slot)
    edge=any(t in valid for t in slot[:2]) and any(t in valid for t in slot[-2:])
    peak_slots=[tstar.replace(minute=0,second=0,microsecond=0)+timedelta(hours=k) for k in (-2,-1,0,1)]
    peak_ok=sum(t in valid for t in peak_slots)>=3 and any(t in valid for t in peak_slots[:2]) and any(t in valid for t in peak_slots[2:])
    if not (coverage>=18 and edge and peak_ok):return None,dict(coverage=coverage,edge=edge,peak_ok=peak_ok,censored=True)
    vals=[float(valid[t]['sknt']) for t in slot if t in valid]
    if any(float(r['gust_sknt'])<float(r['sknt']) for r in valid.values() if r.get('gust_sknt') not in ('',None)):return None,dict(reason='gust_less_than_sustained')
    return max(vals),dict(coverage=coverage,edge=edge,peak_ok=peak_ok,censored=False)

def check_before_run(ns):
    if not ns.lead_frozen:raise SystemExit('NOT FROZEN: Lead must explicitly freeze PREREG_v2 before any observation pairing')
    if not all((ns.tracks,ns.stations,ns.observations,ns.output)):raise SystemExit('all offline inputs/output required')
    out=Path(ns.output)
    if out.exists():raise FileExistsError(out)
    ss=rows(ns.stations);by_event=defaultdict(list)
    for r in ss:
        if station_allowed(r):by_event[r['event']].append(r)
    eligible=[e for e,s in by_event.items() if len(s)>=3]
    if len(eligible)<15:raise SystemExit(f'NO-GO: historically verified ASOS height QC gives only {len(eligible)} events x >=3; no (a) execution')
    return ss,eligible

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--tracks');p.add_argument('--stations');p.add_argument('--observations');p.add_argument('--output');p.add_argument('--lead-frozen',action='store_true');p.add_argument('--landfalls',help='CSV event,landfall_utc');p.add_argument('--adapter-verified',action='store_true')
    ns=p.parse_args();ss,eligible=check_before_run(ns)
    if not ns.landfalls:raise SystemExit('landfall manifest required')
    # H08 keeps its native B; radius and pressure must be provided by an
    # independently audited upstream BEST radii fitter. Abort if unverified.
    if not ns.adapter_verified:raise SystemExit('MODEL ADAPTER NOT VERIFIED: numerical equivalence test of radius fitter against H08 is required; no pairing done')
    import importlib.util,numpy as np,xarray as xr
    base=Path(__file__).resolve().parent.parent/'v1/chain_a_v1.py'
    spec=importlib.util.spec_from_file_location('v1_kernel',base)
    kernel=importlib.util.module_from_spec(spec);sys.modules[spec.name]=kernel;spec.loader.exec_module(kernel)
    land=kernel.get_land()
    landfalls={r['event']:dt(r['landfall_utc']) for r in rows(ns.landfalls)}
    tracks=defaultdict(list)
    for r in rows(ns.tracks):tracks[r['event']].append(r)
    obs=defaultdict(list)
    for r in rows(ns.observations):obs[(r['event'],r['station'])].append(r)
    result=[]
    for event in sorted(eligible):
        candidates=byevent_stations=[r for r in ss if r['event']==event and station_allowed(r)]
        nodes=sorted(tracks[event],key=lambda r:dt(r['time_utc']))
        if len(nodes)<2 or event not in landfalls:raise ValueError(f'missing BEST track or landfall: {event}')
        times=[dt(r['time_utc']) for r in nodes]
        ds=xr.Dataset(data_vars={
            'lat':('time',[float(r['lat']) for r in nodes]),
            'lon':('time',[float(r['lon']) for r in nodes]),
            'max_sustained_wind':('time',[float(r['vmax_kt']) for r in nodes]),
            'central_pressure':('time',[float(r['pc_hpa']) for r in nodes]),
            'environmental_pressure':('time',[float(r['penv_hpa']) for r in nodes]),
            'radius_max_wind':('time',[float(r['rmw_nmi']) for r in nodes]),
            'time_step':('time',[.25]+[(times[i]-times[i-1]).total_seconds()/3600 for i in range(1,len(times))])},
            coords={'time':np.array([np.datetime64(t.replace(tzinfo=None),'ns') for t in times])},
            attrs={'max_sustained_wind_unit':'knots','central_pressure_unit':'mbar'})
        # Unlike a port of windfield code this calls the frozen v1 H08 kernel.
        st=[dict(station=r['station'],lat=float(r['lat']),lon=float(r['lon'])) for r in candidates]
        sustained,gust,_=kernel.predict(ds,st,land)
        for j,r in enumerate(candidates):
            mask=[k for k,t in enumerate(times) if abs((t-landfalls[event]).total_seconds())<=12*3600]
            if not mask:raise ValueError(f'no model nodes in landfall window: {event}')
            ix=max(mask,key=lambda k:sustained[k,j]);tstar=times[ix]
            observed,qc=window_qc(obs[(event,r['station'])],landfalls[event],tstar)
            pred=float(sustained[ix,j]);err=(pred/observed-1 if observed and observed>0 else None)
            result.append(dict(event=event,station=r['station'],tstar=tstar.isoformat(),pred_sknt=pred,obs_sknt=observed,error=err,qc=json.dumps(qc)))
    metrics=[r['error'] for r in result if r['error'] is not None]
    if not metrics:raise ValueError('no scoreable station')
    with Path(ns.output).open('x',newline='') as f:
        writer=csv.DictWriter(f,result[0].keys());writer.writeheader();writer.writerows(result)
    print(json.dumps(dict(events=len(eligible),stations=len(metrics),median_abs_error=statistics.median(map(abs,metrics)),median_bias=statistics.median(metrics))))

if __name__=='__main__':main()
