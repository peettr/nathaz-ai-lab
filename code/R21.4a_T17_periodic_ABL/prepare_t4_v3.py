#!/usr/bin/env python3
"""Prepare a fresh, Linux-spooled T4 group from frozen T4 payload and T15 controller."""
from pathlib import Path
import shutil, json, hashlib, datetime, os
base=Path(__file__).resolve().parent
old=base/'big6_periodic_t4_20261121_0800'
template=base/'big6v3_periodic_t15_k2_20261121_103455'
name='big6v3_periodic_t4_'+datetime.datetime.now().strftime('%Y%m%d_%H%M%S')
archive=base/name
linux=Path.home()/'luw_tmp'/name
archive.mkdir();linux.mkdir(parents=True)
inputs=['worker_native.py','native_analysis.py','analyze_longspin.py','remote_B.py','assert_T17.py','t17b_stage.tar.gz','t17b_manifest.json','stub_native.py','machine.py','NATIVE_PRODUCER_APPROVED.ok']
for n in inputs:shutil.copy2(old/n,linux/n)
s=template.joinpath('controller_hardened.py').read_text()
s=s.replace('T17 T15 pair','T17 T4 pair').replace('CAP=11.5','CAP=10.0').replace("CASES=('t15_s1','t15_s2')","CASES=('t4_s1','t4_s2')").replace('T17 big6v3 T15 #5cfca225','T17 big6v3 T4 #47634124')
s=s.replace("if plan['two_case_upper_CU']>=CAP:","if plan['first_case_upper_CU']>=CAP:")
s=s.replace("margin=cut-time.time()-(2*plan['worst_case_solver_s']+plan['fixed_overhead_s'])","margin=cut-time.time()-(plan['worst_case_solver_s']+plan['fixed_overhead_s'])")
s=s.replace('PRELAUNCH_TWO_CASE_MARGIN_S','PRELAUNCH_FIRST_CASE_MARGIN_S')
s=s.replace('budget cannot fit two cases','budget cannot fit first case')
# Changing live files are snapshots, never overwritten in the project archive.
s=s.replace("if sha(q)!=sha(p):raise IOError('different archived milestone '+str(q))", "if sha(q)!=sha(p):\n      q=q.with_name(q.name+'.milestone_'+str(int(time.time())))\n      tmp.rename(q)\n      break")
# This case can stop after one verified case if the second does not fit the remaining CU.
(linux/'controller_hardened.py').write_text(s)
plan=json.loads((old/'SESSION_PLAN.json').read_text());plan['single_session_cap_CU']=10.0
(linux/'SESSION_PLAN.json').write_text(json.dumps(plan,indent=2)+'\n')
card=(template/'EXPERIMENT_CARD.md').read_text().replace('T15 k2','T4 first-layer').replace('T15 #5cfca225','T4 #47634124').replace('≤11.5 CU','≤10 CU').replace(str(template),str(archive)).replace('d8a50fca3f7b4e4b9aa6021722eea23952ea0f20a99d0f3ce0b1c9eae6915399',hashlib.sha256((linux/'t17b_stage.tar.gz').read_bytes()).hexdigest())
(linux/'EXPERIMENT_CARD.md').write_text(card)
for n in ['controller_hardened.py','worker_native.py','native_analysis.py','analyze_longspin.py','remote_B.py','assert_T17.py','t17b_stage.tar.gz','t17b_manifest.json','SESSION_PLAN.json','machine.py']:
 assert (linux/n).exists()
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
(linux/'PREFLIGHT.ok').write_text(json.dumps({n:sha(linux/n) for n in ['worker_native.py','native_analysis.py','analyze_longspin.py','remote_B.py','assert_T17.py','t17b_stage.tar.gz','t17b_manifest.json','SESSION_PLAN.json','machine.py']},indent=2)+'\n')
(linux/'PAYLOAD_SHA256.json').write_text(json.dumps({n:sha(linux/n) for n in inputs if (linux/n).is_file()},indent=2)+'\n')
(linux/'PATH_PAYLOAD_MAP.md').write_text('worker_native.py, native_analysis.py, analyze_longspin.py, remote_B.py, assert_T17.py, t17b_stage.tar.gz, t17b_manifest.json: same-name PAYLOAD; t17b_budget.json: generated by controller; pack_stage/periodic_t4/src: extracted from t17b_stage.tar.gz; stub_native.py: fixture only.\n')
# Archive only immutable preparation files; live evidence is synchronized by controller.
for p in linux.iterdir():
 if p.is_file():shutil.copy2(p,archive/p.name)
print('ARCHIVE',archive,'LINUX',linux,'SOURCE_SHA',sha(linux/'t17b_stage.tar.gz'))
