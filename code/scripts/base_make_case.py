#!/usr/bin/env python3
"""L26.11 S1: generate square-cylinder IDDES case (D=1, U=1, Re=22000).
usage: make_case.py <outdir> <coupled: true|false> <endTime> <writeIntervalSteps> [dt=0.002] [libname=libDEScoverDelta]"""
import os, sys
out, coupled, endT, wint = sys.argv[1], sys.argv[2], float(sys.argv[3]), int(sys.argv[4])
NU = 1.0/22000.0
DT = float(sys.argv[5]) if len(sys.argv) > 5 else 0.002
LIB = sys.argv[6] if len(sys.argv) > 6 else "libDEScoverDelta"
H = r"""/*--------------------------------*- C++ -*----------------------------------*\
  L26.11 DEScover held-out test (square cylinder Re=22000), generated by make_case.py
\*---------------------------------------------------------------------------*/
FoamFile { version 2.0; format ascii; class %s; object %s; }
"""
def w(rel, cls, obj, body):
    p = os.path.join(out, rel); os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, "w").write(H % (cls, obj) + body)

# ---------------- blockMesh ----------------
X = [-4.5, -0.5, 0.5, 15.0]; Y = [-7.0, -0.5, 0.5, 7.0]; Z = [0.0, 4.0]
NX = [64, 64, 150]; NY = [64, 64, 64]; NZ = 40
GX = ["0.0184", "((0.5 0.5 8) (0.5 0.5 0.125))", "((0.1 40 26) (0.9 110 1))"]
GY = ["0.0098", "((0.5 0.5 8) (0.5 0.5 0.125))", "102"]
def v(i, j, k): return i + 4*j + 16*k
verts = [(x, y, z) for z in Z for y in Y for x in X]
blocks, hexes = [], {}
for j in range(3):
    for i in range(3):
        if (i, j) == (1, 1): continue
        hx = [v(i,j,0), v(i+1,j,0), v(i+1,j+1,0), v(i,j+1,0), v(i,j,1), v(i+1,j,1), v(i+1,j+1,1), v(i,j+1,1)]
        hexes[(i, j)] = hx
        blocks.append("    hex (%s) (%d %d %d) simpleGrading (%s %s 1)" % (" ".join(map(str, hx)), NX[i], NY[j], NZ, GX[i], GY[j]))
LF = {"xmin": (0,4,7,3), "xmax": (1,2,6,5), "ymin": (0,1,5,4), "ymax": (3,7,6,2), "zmin": (0,3,2,1), "zmax": (4,5,6,7)}
def face(ij, f): hx = hexes[ij]; return "(" + " ".join(str(hx[k]) for k in LF[f]) + ")"
pat = {
 "inlet":  [face((0,j),"xmin") for j in range(3)],
 "outlet": [face((2,j),"xmax") for j in range(3)],
 "bottom": [face((i,0),"ymin") for i in range(3)],
 "top":    [face((i,2),"ymax") for i in range(3)],
 "cylinder": [face((1,0),"ymax"), face((1,2),"ymin"), face((0,1),"xmax"), face((2,1),"xmin")],
 "front":  [face(ij,"zmin") for ij in hexes],
 "back":   [face(ij,"zmax") for ij in hexes],
}
types = {"inlet":"patch","outlet":"patch","bottom":"patch","top":"patch","cylinder":"wall"}
bnd = []
for n, fl in pat.items():
    if n in ("front","back"):
        nb = "back" if n=="front" else "front"
        bnd.append("    %s { type cyclic; neighbourPatch %s; faces (%s); }" % (n, nb, " ".join(fl)))
    else:
        bnd.append("    %s { type %s; faces (%s); }" % (n, types[n], " ".join(fl)))
w("system/blockMeshDict", "dictionary", "blockMeshDict",
  "scale 1;\nvertices\n(\n" + "\n".join("    (%g %g %g)" % p for p in verts) + "\n);\nblocks\n(\n" + "\n".join(blocks) +
  "\n);\nedges ();\nboundary\n(\n" + "\n".join(bnd) + "\n);\nmergePatchPairs ();\n")

# ---------------- constant ----------------
w("constant/transportProperties", "dictionary", "transportProperties",
  "transportModel Newtonian;\nnu %.8e;\n" % NU)
w("constant/turbulenceProperties", "dictionary", "turbulenceProperties", """simulationType LES;
LES
{
    LESModel        SpalartAllmarasIDDES;
    turbulence      on;
    printCoeffs     on;
    delta           IDDESDeltaDEScover;
    IDDESDeltaDEScoverCoeffs
    {
        Cw          0.15;
        fdLimit     0.01;
        Clim        0.15;
        coupled     %s;
        hmaxOuter   DeltaLiutexTilde;
        DeltaLiutexTildeCoeffs
        {
            deltaCoeff  1.035;
        }
    }
    IDDESDeltaCoeffs
    {
        Cw          0.15;
    }
}
""" % coupled)

# ---------------- 0 ----------------
nut0 = 3*NU
def fld(name, cls, dim, internal, bcs):
    body = "dimensions %s;\ninternalField uniform %s;\nboundaryField\n{\n" % (dim, internal)
    for p, b in bcs: body += "    %s { %s }\n" % (p, b)
    body += "    front { type cyclic; }\n    back { type cyclic; }\n}\n"
    w("0/"+name, cls, name, body)
fld("U", "volVectorField", "[0 1 -1 0 0 0 0]", "(1 0 0)", [
    ("inlet", "type fixedValue; value uniform (1 0 0);"),
    ("outlet", "type inletOutlet; inletValue uniform (0 0 0); value uniform (1 0 0);"),
    ("top", "type slip;"), ("bottom", "type slip;"), ("cylinder", "type noSlip;")])
fld("p", "volScalarField", "[0 2 -2 0 0 0 0]", "0", [
    ("inlet", "type zeroGradient;"), ("outlet", "type fixedValue; value uniform 0;"),
    ("top", "type slip;"), ("bottom", "type slip;"), ("cylinder", "type zeroGradient;")])
fld("nuTilda", "volScalarField", "[0 2 -1 0 0 0 0]", "%.6e" % nut0, [
    ("inlet", "type fixedValue; value uniform %.6e;" % nut0),
    ("outlet", "type inletOutlet; inletValue uniform %.6e; value uniform %.6e;" % (nut0, nut0)),
    ("top", "type slip;"), ("bottom", "type slip;"), ("cylinder", "type fixedValue; value uniform 0;")])
fld("nut", "volScalarField", "[0 2 -1 0 0 0 0]", "0", [
    ("inlet", "type calculated; value uniform 0;"), ("outlet", "type calculated; value uniform 0;"),
    ("top", "type calculated; value uniform 0;"), ("bottom", "type calculated; value uniform 0;"),
    ("cylinder", "type nutUSpaldingWallFunction; value uniform 0;")])

# ---------------- system ----------------
w("system/fvSchemes", "dictionary", "fvSchemes", """ddtSchemes { default backward; }
gradSchemes { default Gauss linear; }
divSchemes
{
    default         none;
    div(phi,U)      Gauss DEShybrid
        linear                  // scheme 1 (paper 2.3.2)
        limitedCubic 1          // scheme 2 (paper 2.3.2)
        delta                   // LES delta
        0.65                    // CDES (paper 2.3.2)
        1.0                     // Uref (= U_inf)
        1.0                     // Lref (= D)
        0.0                     // sigma min
        1.0                     // sigma max
        1.0                     // B limiter (assumption, tutorial value)
        10.0;                   // nut limiter (assumption, tutorial value)
    div(phi,nuTilda) Gauss limitedLinear 1;
    div((nuEff*dev2(T(grad(U))))) Gauss linear;
}
laplacianSchemes { default Gauss linear corrected; }
interpolationSchemes { default linear; }
snGradSchemes { default corrected; }
wallDist { method meshWave; nRequired yes; }
""")
w("system/fvSolution", "dictionary", "fvSolution", """solvers
{
    p { solver GAMG; smoother DICGaussSeidel; tolerance 1e-6; relTol 0.05; }
    pFinal { $p; relTol 0; }
    "(U|nuTilda)" { solver PBiCG; preconditioner DILU; tolerance 1e-6; relTol 0.1; }
    "(U|nuTilda)Final" { $U; relTol 0; }
}
PIMPLE
{
    nOuterCorrectors 1;
    nCorrectors 2;
    nNonOrthogonalCorrectors 1;
}
""")
w("system/decomposeParDict", "dictionary", "decomposeParDict",
  "numberOfSubdomains 48;\nmethod scotch;\n")
zones = """
        actions
        (
            { name frontFaceSet; type cellSet; action new; source boxToCell; box (-0.53 -0.4 -1) (-0.5 0.4 5); }
            { name frontFace; type cellZoneSet; action new; source setToCellZone; set frontFaceSet; }
            { name sideWallSet; type cellSet; action new; source boxToCell; box (-0.5 0.5 -1) (0.5 0.53 5); }
            { name sideWallSet; type cellSet; action add; source boxToCell; box (-0.5 -0.53 -1) (0.5 -0.5 5); }
            { name sideWall; type cellZoneSet; action new; source setToCellZone; set sideWallSet; }
            { name shearSet; type cellSet; action new; source boxToCell; box (-0.3 0.55 -1) (1.5 1.0 5); }
            { name shearSet; type cellSet; action add; source boxToCell; box (-0.3 -1.0 -1) (1.5 -0.55 5); }
            { name shearLayer; type cellZoneSet; action new; source setToCellZone; set shearSet; }
            { name wakeSet; type cellSet; action new; source boxToCell; box (1.0 -1.0 -1) (4.0 1.0 5); }
            { name wake; type cellZoneSet; action new; source setToCellZone; set wakeSet; }
        );"""
open(os.path.join(out, "system/topoSetDict"), "w").write(H % ("dictionary", "topoSetDict") + zones.replace("        actions", "actions") + "\n")
vfv = ""
for z in ["frontFace", "sideWall", "shearLayer", "wake"]:
    vfv += """    dstat_%s
    {
        type volFieldValue; libs (fieldFunctionObjects);
        regionType cellZone; name %s; operation volAverage;
        fields (delta hmax hmaxOuter IDDESDeltaDEScover.shield nut);
        writeFields false; writeControl timeStep; writeInterval 50; log false;
    }
""" % (z, z)
w("system/controlDict", "dictionary", "controlDict", """application     pimpleFoam;
libs            ("/groups/kareem/[用户]/L26_11_DESCOVER_20261025/lib/%s.so");
startFrom       latestTime;
startTime       0;
stopAt          endTime;
endTime         %g;
deltaT          %g;
writeControl    timeStep;
writeInterval   %d;
purgeWrite      0;
writeFormat     binary;
writePrecision  8;
writeCompression off;
timeFormat      general;
timePrecision   8;
runTimeModifiable false;
functions
{
    deltaFields
    {
        type writeObjects; libs (utilityFunctionObjects);
        objects (delta hmax hmaxOuter IDDESDeltaDEScover.shield);
        writeOption anyWrite; writeControl timeStep; writeInterval %d;
    }
%s    forceCoeffs1
    {
        type forceCoeffs; libs (forces); patches (cylinder);
        rho rhoInf; rhoInf 1; CofR (0 0 2);
        liftDir (0 1 0); dragDir (1 0 0); pitchAxis (0 0 1);
        magUInf 1; lRef 1; Aref 4;
        writeControl timeStep; writeInterval 1; log false;
    }
    courant { type CourantNo; libs (fieldFunctionObjects); writeControl writeTime; }
}
""" % (LIB, endT, DT, wint, wint, vfv))
print("case written:", out)
